std::string ToUtf8(const std::wstring& s) { return fs::path(s).string(); }
std::wstring ToWide(const std::string& s) { return fs::path(s).wstring(); }

std::wstring Join(const std::wstring& a, const std::wstring& b)
{
    return a + FILE_SEPARATOR_STR + b;
}

// Working directory of the test process (the staged fixture directory).
const std::wstring kCwd = []() -> std::wstring
{
    return fs::current_path().wstring();
}();

bool ReadFileBytes(const std::string& path, std::string* out)
{
    std::ifstream f(path, std::ios::binary);
    if (!f.is_open())
        return false;
    out->assign(std::istreambuf_iterator<char>(f), std::istreambuf_iterator<char>());
    return !out->empty();
}

// NSDirectory::Exists is a DIRECTORY check on Linux (stat + S_ISDIR) — it
// returns false for plain files. Existence of files must go through NSFile.
bool FileExists(const std::wstring& path)
{
    return NSFile::CFileBinary::Exists(path);
}

std::string Utf16Le(const std::string& s)
{
    std::string out;
    out.reserve(s.size() * 2);
    for (char c : s)
    {
        out.push_back(c);
        out.push_back('\0');
    }
    return out;
}

size_t FindUtf16Le(const std::string& data, const std::string& ascii)
{
    return data.find(Utf16Le(ascii));
}

// Walks back from payloadPos to the 0xFA record start byte.
size_t FindRecordStart(const std::string& data, size_t payloadPos, size_t window = 512)
{
    const size_t begin = payloadPos > window ? payloadPos - window : 0;
    for (size_t i = payloadPos; i-- > begin;)
    {
        if (static_cast<unsigned char>(data[i]) == 0xfa)
            return i;
    }
    return std::string::npos;
}

int32_t ReadInt32Le(const std::string& d, size_t pos)
{
    return static_cast<int32_t>(
        static_cast<uint32_t>(static_cast<unsigned char>(d[pos])) |
        static_cast<uint32_t>(static_cast<unsigned char>(d[pos + 1])) << 8 |
        static_cast<uint32_t>(static_cast<unsigned char>(d[pos + 2])) << 16 |
        static_cast<uint32_t>(static_cast<unsigned char>(d[pos + 3])) << 24);
}

size_t CountOccurrences(const std::string& s, const std::string& sub)
{
    size_t count = 0;
    size_t pos = 0;
    while ((pos = s.find(sub, pos)) != std::string::npos)
    {
        ++count;
        pos += sub.size();
    }
    return count;
}

// Returns the first element opened by openTag .. closed by closeTag that
// contains mustContain (element text including both tags).
std::string FindElementWith(const std::string& xml, const std::string& openTag,
                            const std::string& closeTag, const std::string& mustContain)
{
    size_t pos = 0;
    while ((pos = xml.find(openTag, pos)) != std::string::npos)
    {
        const size_t end = xml.find(closeTag, pos);
        if (end == std::string::npos)
            return std::string();
        const std::string element = xml.substr(pos, end + closeTag.size() - pos);
        if (element.find(mustContain) != std::string::npos)
            return element;
        pos = end + closeTag.size();
    }
    return std::string();
}

std::string EscapeXml(const std::string& s)
{
    std::string out;
    out.reserve(s.size());
    for (char c : s)
    {
        switch (c)
        {
        case '&': out += "&amp;"; break;
        case '<': out += "&lt;"; break;
        case '>': out += "&gt;"; break;
        case '"': out += "&quot;"; break;
        case '\'': out += "&apos;"; break;
        default: out += c; break;
        }
    }
    return out;
}

// ---------------------------------------------------------------------------
// In-process conversion (mirrors OOXML/test/common.cpp: x2t converts
// according to a TaskQueueDataConvert params file; the output format follows
// m_sFileTo's extension — .bin = binary intermediate, .pptx = package).
// ---------------------------------------------------------------------------

std::string CreateParamsFile(const std::string& from, const std::string& to,
                             const std::string& tempDir)
{
    static int counter = 0;
    const std::string path = tempDir + "/params_" + std::to_string(counter++) + ".xml";
    const std::string xml =
        "<?xml version=\"1.0\" encoding=\"utf-8\"?>"
        "<TaskQueueDataConvert>"
        "<m_sFileFrom>" + EscapeXml(from) + "</m_sFileFrom>"
        "<m_sFileTo>" + EscapeXml(to) + "</m_sFileTo>"
        "<m_bFromChanges>false</m_bFromChanges>"
        "<m_bDontSaveAdditional>true</m_bDontSaveAdditional>"
        "<m_sTempDir>" + EscapeXml(tempDir) + "</m_sTempDir>"
        "<m_nCsvTxtEncoding>46</m_nCsvTxtEncoding>"
        "<m_nCsvDelimiter>4</m_nCsvDelimiter>"
        "</TaskQueueDataConvert>";
    std::ofstream f(path, std::ios::binary);
    f << xml;
    return path;
}

int Convert(const std::string& paramsFile)
{
    x2tchar* args[2];
    args[0] = (x2tchar*)"";
#if defined(_WIN32) || defined(_WIN64)
    const std::wstring wide = ToWide(paramsFile);
    args[1] = (x2tchar*)wide.c_str();
#else
    // X2T_Convert takes narrow UTF-8 char* on non-Windows (src/dylib/x2t.h);
    // casting a wchar_t* directly truncates the path (see ooxml_test, PR #166).
    args[1] = (x2tchar*)paramsFile.c_str();
#endif
    return X2T_Convert(2, args);
}

// ---------------------------------------------------------------------------
// Round trip
// ---------------------------------------------------------------------------

struct RoundTripResult
{
    bool ok = false;
    bool authorsIsModern = false;   // authors part found at ppt/authors.xml
    std::string bin;                // raw bytes of the .bin intermediate
    std::string authorsPart;        // ppt/authors.xml or ppt/commentAuthors.xml
    std::string commentsPart;      // the single part under ppt/comments/
    std::string error;
};

// Converts `fixtureName` (working-dir relative) through the .bin intermediate
// and back to .pptx, unpacks the result and locates the authors/comments parts.
RoundTripResult RoundTrip(const std::string& fixtureName, const std::wstring& workName)
{
    RoundTripResult r;

    const std::wstring work = Join(kCwd, workName);
    const std::string work8 = ToUtf8(work);
    const std::string fixture8 = ToUtf8(Join(kCwd, ToWide(fixtureName)));
    const std::string binPath = work8 + "/intermediate.bin";
    const std::string pptxPath = work8 + "/roundtrip.pptx";

    NSDirectory::DeleteDirectory(work);
    NSDirectory::CreateDirectory(work);

    // Each conversion gets its own m_sTempDir: x2t extracts the pptx INPUT
    // into <temp>/pptx_unpacked on the pptx->bin leg and writes the rebuilt
    // package into <temp>/pptx_unpacked on the bin->pptx leg, so a shared
    // temp dir would splice input leftovers into the output package.
    const std::string tempToBin = work8 + "/t_to_bin";
    const std::string tempToPptx = work8 + "/t_to_pptx";
    NSDirectory::CreateDirectory(ToWide(tempToBin));
    NSDirectory::CreateDirectory(ToWide(tempToPptx));

    const int rcToBin = Convert(CreateParamsFile(fixture8, binPath, tempToBin));
    if (!ReadFileBytes(binPath, &r.bin) || r.bin.size() < 64)
    {
        r.error = "pptx->bin produced no usable intermediate (X2T_Convert rc=" +
                  std::to_string(rcToBin) + ")";
        return r;
    }

    const int rcToPptx = Convert(CreateParamsFile(binPath, pptxPath, tempToPptx));
    const std::wstring unpacked = Join(work, L"unpacked");
    NSDirectory::DeleteDirectory(unpacked);
    NSDirectory::CreateDirectory(unpacked);
    COfficeUtils utils(NULL);
    utils.ExtractToDirectory(ToWide(pptxPath), unpacked, NULL, 0);
    if (!FileExists(Join(unpacked, L"[Content_Types].xml")))
    {
        r.error = "bin->pptx produced no extractable package (X2T_Convert rc=" +
                  std::to_string(rcToPptx) + ")";
        return r;
    }

    const std::string unpacked8 = ToUtf8(unpacked);
    const std::wstring ppt = Join(unpacked, L"ppt");

    // Authors part: modern writers put it at ppt/authors.xml, classic writers
    // at ppt/commentAuthors.xml.
    if (FileExists(Join(ppt, L"authors.xml")))
    {
        r.authorsIsModern = true;
        ReadFileBytes(unpacked8 + "/ppt/authors.xml", &r.authorsPart);
    }
    else if (FileExists(Join(ppt, L"commentAuthors.xml")))
    {
        ReadFileBytes(unpacked8 + "/ppt/commentAuthors.xml", &r.authorsPart);
    }

    // Comments part: exactly one XML part under ppt/comments/.
    const fs::path commentsDir = fs::path(unpacked8) / "ppt" / "comments";
    std::vector<std::string> commentParts;
    if (fs::exists(commentsDir))
    {
        for (fs::directory_iterator it(commentsDir), end; it != end; ++it)
        {
            if (it->path().extension() == ".xml")
                commentParts.push_back(it->path().string());
        }
    }

    if (r.authorsPart.empty())
    {
        r.error = "round-tripped package has no authors part (expected ppt/authors.xml "
                  "or ppt/commentAuthors.xml)";
        return r;
    }
    if (commentParts.size() != 1)
    {
        r.error = "expected exactly one comments part under ppt/comments/, found " +
                  std::to_string(commentParts.size());
        return r;
    }
    ReadFileBytes(commentParts[0], &r.commentsPart);

    r.ok = true;
    return r;
}

const RoundTripResult& ModernResult()
{
    static const RoundTripResult r = RoundTrip("modern_comments.pptx", L"work_modern");
    return r;
}

const RoundTripResult& ClassicResult()
{
    static const RoundTripResult r = RoundTrip("classic_comments.pptx", L"work_classic");
    return r;
}

const RoundTripResult& MissingIdsResult()
{
    static const RoundTripResult r =
        RoundTrip("modern_comments_no_author_ids.pptx", L"work_missing_ids");
    return r;
}

