// ---------------------------------------------------------------------------
// Modern fixture: GUID authors + shuffled modern comments.
// ---------------------------------------------------------------------------

TEST(ModernRoundTrip, StaysModern)
{
    const RoundTripResult& r = ModernResult();
    ASSERT_TRUE(r.ok) << r.error;
    EXPECT_TRUE(r.authorsIsModern);
    EXPECT_NE(r.authorsPart.find("p188:authorLst"), std::string::npos);
    EXPECT_EQ(r.authorsPart.find("p:cmAuthorLst"), std::string::npos);
    EXPECT_NE(r.commentsPart.find("p188:cmLst"), std::string::npos);
    EXPECT_EQ(r.commentsPart.find("p:cmLst"), std::string::npos);
}

TEST(ModernRoundTrip, AuthorIdentitiesPreserved)
{
    const RoundTripResult& r = ModernResult();
    ASSERT_TRUE(r.ok) << r.error;

    EXPECT_EQ(CountOccurrences(r.authorsPart, "<p188:author "), 3u);
    for (const AuthorInfo* a : {&kAlice, &kBob, &kCarol})
    {
        const std::string element = FindElementWith(
            r.authorsPart, "<p188:author ", "</p188:author>",
            std::string("name=\"") + a->name + "\"");
        ASSERT_FALSE(element.empty()) << "author " << a->name << " vanished from the authors part";
        EXPECT_NE(element.find(std::string("initials=\"") + a->initials + "\""), std::string::npos)
            << "initials of " << a->name << " lost";
        EXPECT_NE(element.find(a->guid), std::string::npos)
            << "GUID of " << a->name << " lost — the round trip downgraded author identity";
    }
}

TEST(ModernRoundTrip, CommentAuthorMappingPreserved)
{
    const RoundTripResult& r = ModernResult();
    ASSERT_TRUE(r.ok) << r.error;

    EXPECT_EQ(CountOccurrences(r.commentsPart, "<p188:cm "), 3u);

    size_t previousPos = std::string::npos;
    for (const AuthorInfo* a : kCommentOrder)
    {
        const std::string createdAttr = std::string("created=\"") + a->commentDate + "\"";
        const std::string element = FindElementWith(
            r.commentsPart, "<p188:cm ", "</p188:cm>", createdAttr);
        ASSERT_FALSE(element.empty()) << "comment created " << a->commentDate << " vanished";
        EXPECT_NE(element.find(std::string("authorId=\"") + a->guid + "\""), std::string::npos)
            << "comment by " << a->name << " lost its authorId";
        EXPECT_NE(element.find(a->commentText), std::string::npos)
            << "comment by " << a->name << " lost its text";

        const size_t pos = r.commentsPart.find(createdAttr);
        if (previousPos != std::string::npos)
        {
            EXPECT_LT(previousPos, pos) << "comment document order changed";
        }
        previousPos = pos;
    }
}

// The identity sdkjs actually reads: the pptx->bin leg must write the author
// idx attribute (tag 0x00) on every author record and the matching authorIdx
// on every comment record. This is the core regression of issue #143 —
// without the fix these attributes are absent from the intermediate.
TEST(ModernRoundTrip, BinCarriesAuthorIdentity)
{
    const RoundTripResult& r = ModernResult();
    ASSERT_TRUE(r.ok) << r.error;

    for (const AuthorInfo* a : {&kAlice, &kBob, &kCarol})
    {
        // Author record: 0xFA, attr tag 0x00, int32 idx, type, length, name.
        const size_t namePos = FindUtf16Le(r.bin, a->name);
        ASSERT_NE(namePos, std::string::npos)
            << "author name " << a->name << " missing from the binary intermediate";
        const size_t record = FindRecordStart(r.bin, namePos);
        ASSERT_NE(record, std::string::npos) << "no 0xFA record byte before " << a->name;
        ASSERT_LT(record + 6, r.bin.size());
        EXPECT_EQ(static_cast<unsigned char>(r.bin[record + 1]), 0x00u)
            << "author record of " << a->name << " carries no idx attribute (#143 regression)";
        EXPECT_EQ(ReadInt32Le(r.bin, record + 2), a->binIdx)
            << "author record of " << a->name << " has the wrong idx";

        // The GUID id attribute must survive into the bin, next to the name
        // (initials and id follow the name inside the same record).
        const size_t guidPos = FindUtf16Le(r.bin, a->guid);
        ASSERT_NE(guidPos, std::string::npos)
            << "author GUID of " << a->name << " missing from the binary intermediate";
        EXPECT_GT(guidPos, namePos)
            << "author GUID of " << a->name << " not part of its author record";
        EXPECT_LT(guidPos - namePos, 256u)
            << "author GUID of " << a->name << " not adjacent to its record";

        // Comment record: 0xFA, attr tag 0x00, int32 authorIdx, type, length, date.
        const size_t datePos = FindUtf16Le(r.bin, a->commentDate);
        ASSERT_NE(datePos, std::string::npos) << "comment date missing from the binary intermediate";
        const size_t commentRecord = FindRecordStart(r.bin, datePos);
        ASSERT_NE(commentRecord, std::string::npos);
        ASSERT_LT(commentRecord + 6, r.bin.size());
        EXPECT_EQ(static_cast<unsigned char>(r.bin[commentRecord + 1]), 0x00u)
            << "comment of " << a->name << " carries no authorIdx attribute (#143 regression)";
        EXPECT_EQ(ReadInt32Le(r.bin, commentRecord + 2), a->binIdx)
            << "comment of " << a->name << " points at the wrong author";
    }
}

