TEST(ClassicRoundTrip, StaysClassic)
{
    const RoundTripResult& r = ClassicResult();
    ASSERT_TRUE(r.ok) << r.error;
    EXPECT_FALSE(r.authorsIsModern);
    EXPECT_NE(r.authorsPart.find("p:cmAuthorLst"), std::string::npos);
    EXPECT_EQ(r.authorsPart.find("p188"), std::string::npos)
        << "modern p188 markup leaked into a classic document";
    EXPECT_NE(r.commentsPart.find("p:cmLst"), std::string::npos);
    EXPECT_EQ(r.commentsPart.find("p188"), std::string::npos)
        << "modern p188 markup leaked into a classic document";
}

TEST(ClassicRoundTrip, AuthorIdentitiesPreserved)
{
    const RoundTripResult& r = ClassicResult();
    ASSERT_TRUE(r.ok) << r.error;

    EXPECT_EQ(CountOccurrences(r.authorsPart, "<p:cmAuthor "), 3u);
    // The classic fixture maps Alice->0, Bob->1, Carol->2 (make_fixtures.py).
    for (const AuthorInfo* a : {&kAlice, &kBob, &kCarol})
    {
        const std::string element = FindElementWith(
            r.authorsPart, "<p:cmAuthor ", "</p:cmAuthor>",
            std::string("name=\"") + a->name + "\"");
        ASSERT_FALSE(element.empty()) << "author " << a->name << " vanished from the authors part";
        EXPECT_NE(element.find(std::string("id=\"") + std::to_string(a->binIdx - 1) + "\""),
                  std::string::npos)
            << "classic id of " << a->name << " lost";
    }
}

