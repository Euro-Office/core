struct AuthorInfo
{
    const char* name;        // "Alice Author"
    const char* initials;    // "AA"
    const char* guid;        // "{11111111-1111-1111-1111-111111111111}"
    const char* commentText; // "Comment from Alice"
    const char* commentDate; // "2026-10-16T10:01:00Z"
    int binIdx;              // author idx written into the bin intermediate
};

// Document order of the authors part in the fixtures.
const AuthorInfo kAlice = {"Alice Author", "AA",
    "{11111111-1111-1111-1111-111111111111}",
    "Comment from Alice", "2026-10-16T10:01:00Z", 1};
const AuthorInfo kBob = {"Bob Builder", "BB",
    "{22222222-2222-2222-2222-222222222222}",
    "Comment from Bob", "2026-10-16T10:02:00Z", 2};
const AuthorInfo kCarol = {"Carol Carter", "CC",
    "{33333333-3333-3333-3333-333333333333}",
    "Comment from Carol", "2026-10-16T10:00:00Z", 3};

// Document order of the comments parts: deliberately shuffled (Carol, Alice,
// Bob) so an order- or position-based mapping cannot pass by accident.
const AuthorInfo* const kCommentOrder[] = {&kCarol, &kAlice, &kBob};

