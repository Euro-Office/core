// pptx_comments_test — regression suite for modern PowerPoint comments
// (Euro-Office/core issue #143, see also Euro-Office/sdkjs#87).
//
// Modern comments (the Microsoft `p188` extension) identify their authors by
// GUID instead of the classic integer index. Before the fix, the pptx->bin leg
// wrote no author idx / comment authorIdx attribute into the binary
// intermediate, so the editor (sdkjs) defaulted every comment to the first
// author; and a modern author record without any id attribute crashed
// CommentAuthor::toXmlWriter on the bin->pptx leg (unchecked attribute
// dereference).
//
// Each case drives a full in-process round trip pptx -> bin -> pptx through
// X2T_Convert (the same dylib entry point the ooxml_test suite uses) and
// asserts on
//   * the unpacked output package — modernity is preserved in both
//     directions, author GUID/name/initials and per-comment authorId survive
//     in document order, classic documents do not leak p188 markup;
//   * the raw binary intermediate — the idx / authorIdx attribute sdkjs
//     reads when attributing comments. PPTY record layout relevant here:
//     0xFA record byte, then attributes as [tag byte][int32 value] pairs
//     (tag 0x00 = idx on author records, authorIdx on comment records),
//     then the record type byte, int32 length and UTF-16LE payloads.
//
// The three fixtures under ExampleFiles/ are generated by make_fixtures.py;
// work directories (work_*) are left behind in the staged fixture directory
// for post-mortem inspection after a run.

