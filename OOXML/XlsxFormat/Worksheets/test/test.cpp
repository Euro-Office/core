// xlsx_condfmt_test — regression suite for xlsx conditional formatting
// through the XLSB binary intermediate (OOXML/XlsxFormat/Worksheets/
// ConditionalFormatting.cpp, the xlsx cfRule XML <-> XLSB Biff12 records
// conversion: cellIs, expression, colorScale, dataBar, iconSet, top10, dxf
// differential styles, and the Excel 2010 x14 dataBar fixture).
//
// The spreadsheet editor's binary intermediate is XLSB, so each case drives
// a full in-process round trip xlsx -> xlsb -> xlsx through X2T_Convert
// (the same dylib entry point as OOXML/test and pptx_comments_test) and
// asserts on
//   * the unpacked output package — every conditionalFormatting block keeps
//     its rule types, operators, priorities, dxfIds, formulas and sqref
//     ranges, and the dxf styles survive in styles.xml;
//   * the raw sheet part of the .xlsb intermediate — the CF formulas as
//     parsed PtgInt tokens, proving the rules reached the binary leg.
//
// The three fixtures under ExampleFiles/ are generated by make_fixtures.py:
//   condfmt_rules.xlsx — the seven classic rule families, three dxfs;
//   condfmt_edge.xlsx — a dangling dxfId="99" on the "between" rule;
//   condfmt_x14.xlsx — the seed plus the x14 dataBar extension (inline
//     x14:id and the worksheet-level x14:conditionalFormattings extLst);
//     covered as a smoke test — whether the x14 extension itself survives
//     the round trip is not yet verified.
//
// Work directories (work_*) are left behind in the staged fixture directory
// for post-mortem inspection after a run.

