TEST(StylesRoundTrip, DxfStylesPreserved)
{
    const RoundTripResult r = RoundTripRules();
    ASSERT_ROUND_TRIP(r);
    ASSERT_FALSE(r.stylesXml.empty()) << "no styles part in the output";
    EXPECT_NE(std::string::npos, r.stylesXml.find("<dxfs"));
    // All three dxf entries survive; the writer emits the count ATTRIBUTE as
    // 2 for 3 entries (quirk, not pinned) — count the elements instead.
    EXPECT_EQ(3u, CountOccurrences(r.stylesXml, "<dxf>"));
    // dxf colors return with a zeroed alpha channel (FF9C0006 -> 009C0006):
    // assert the RGB payload, not the alpha prefix.
    for (const char* rgb : {"9C0006", "006100", "1F4E79", "FFC7CE", "C6EFCE"})
        EXPECT_NE(std::string::npos, r.stylesXml.find(rgb)) << "missing " << rgb;
}

