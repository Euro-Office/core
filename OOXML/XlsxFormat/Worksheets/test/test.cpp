TEST(XlsbIntermediate, CarriesCfContent)
{
    const RoundTripResult r = RoundTripRules();
    ASSERT_ROUND_TRIP(r);
    ASSERT_FALSE(r.xlsbSheet.empty()) << "no sheet part in the xlsb intermediate";
    // Formulas cross into the Biff12 stream as PARSED TOKEN STREAMS, not
    // wide strings. The constants that survive the round trip (101, 2026)
    // and the between operands (1234, 5678 — dropped on the read leg, see
    // FormulasPreserved) are stored as 16-bit PtgInt tokens: byte 0x1E
    // followed by the little-endian int16 literal. Confirmed against real
    // intermediate bytes: all four appear exactly once in the sheet part,
    // proving the CF rules (and their formula payloads) travel through the
    // binary intermediate under test.
    EXPECT_NE(std::string::npos,
              r.xlsbSheet.find(std::string("\x1e\x65\x00", 3))) << "no PtgInt token for 101";
    EXPECT_NE(std::string::npos,
              r.xlsbSheet.find(std::string("\x1e\xea\x07", 3))) << "no PtgInt token for 2026";
    EXPECT_NE(std::string::npos,
              r.xlsbSheet.find(std::string("\x1e\xd2\x04", 3))) << "no PtgInt token for 1234";
    EXPECT_NE(std::string::npos,
              r.xlsbSheet.find(std::string("\x1e\x2e\x16", 3))) << "no PtgInt token for 5678";
}

