TEST(RulesRoundTrip, FamilyDetailsPreserved)
{
    const RoundTripResult r = RoundTripRules();
    ASSERT_ROUND_TRIP(r);
    // colorScale: three stops with a percentile midpoint and three colors.
    EXPECT_EQ(1u, CountOccurrences(r.sheetXml, "type=\"percentile\""));
    // Numeric attributes come back with fixed precision ("50.000000"):
    // assert the value prefix, not the textual shape.
    EXPECT_NE(std::string::npos, r.sheetXml.find("val=\"50"));
    // The min color returns as its palette-equivalent indexed form
    // (indexed="2" is red FFFF0000); the other two colors stay ARGB.
    const bool hasRedRgb = r.sheetXml.find("FFFF0000") != std::string::npos;
    const bool hasRedIndexed = r.sheetXml.find("indexed=\"2\"") != std::string::npos;
    EXPECT_TRUE(hasRedRgb || hasRedIndexed) << "red min color lost";
    for (const char* color : {"FF00B050", "FF0070C0"})
        EXPECT_NE(std::string::npos, r.sheetXml.find(color)) << "missing " << color;
    // dataBar color.
    EXPECT_NE(std::string::npos, r.sheetXml.find("FF638EC6"));
    // iconSet percent thresholds.
    EXPECT_NE(std::string::npos, r.sheetXml.find("val=\"33"));
    EXPECT_NE(std::string::npos, r.sheetXml.find("val=\"67"));
    // iconSet type preserved (schema-valid 3TrafficLights1; the fixture
    // previously used the invalid "3TrafficLights", which
    // ST_IconSetType::FromString silently maps to 3Arrows — review fix).
    EXPECT_NE(std::string::npos, r.sheetXml.find("iconSet=\"3TrafficLights1\""));
    // top10: rank is a cfRule attribute in SpreadsheetML; preserved as 10.
    EXPECT_NE(std::string::npos, r.sheetXml.find("rank=\"10\""));
    EXPECT_NE(std::string::npos, r.sheetXml.find("type=\"top10\""));
}

