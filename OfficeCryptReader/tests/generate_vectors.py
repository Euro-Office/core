"""Writes reference_vectors.h: data encrypted by implementations other than
core's, which officecrypt_test decrypts with OfficeCryptReader.

- ECMA-376 agile encryption (AES-256, SHA-512) by msoffcrypto-tool
- ODF 1.2 encryption (SHA-256 start key, PBKDF2, AES-256-CBC) and the
  ECMA-376 / ODF write protection hashes with Python's hashlib and the
  cryptography package

Needs: pip install msoffcrypto-tool olefile cryptography
"""

import hashlib
import io
import os
import re
import struct
import base64
import zlib

import olefile
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
from msoffcrypto.method.ecma376_agile import ECMA376Agile

PASSWORD = "Pässwört€"
ASCII_PASSWORD = "Euro-Office"


def lcg_bytes(count, seed):
    """Same generator as LcgBytes() in test.cpp"""
    out = bytearray()
    x = seed
    for _ in range(count):
        x = (x * 1103515245 + 12345) & 0x7FFFFFFF
        out.append((x >> 16) & 0xFF)
    return bytes(out)


def c_array(name, data):
    lines = [",".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return f"static const unsigned char {name}[] = {{\n" + ",\n".join("\t" + l for l in lines) + "\n};\n"


def agile():
    plain = lcg_bytes(5000, 1)  # two 4096 byte segments
    ole = ECMA376Agile.encrypt(PASSWORD, io.BytesIO(plain))
    f = olefile.OleFileIO(io.BytesIO(ole))
    info = f.openstream("EncryptionInfo").read()[8:].decode("utf-8")
    package = f.openstream("EncryptedPackage").read()
    assert struct.unpack("<Q", package[:8])[0] == len(plain)

    def attr(element, name):
        m = re.search(r"<%s\b[^>]*\b%s=\"([^\"]*)\"" % (element, name), info)
        return m.group(1)

    assert attr("keyData", "cipherAlgorithm") == "AES" and attr("keyData", "hashAlgorithm") == "SHA512"
    assert attr("keyData", "keyBits") == "256" and attr("p:encryptedKey", "spinCount") == "100000"
    b = lambda element, name: base64.b64decode(attr(element, name))
    return [
        c_array("c_arAgileSalt", b("p:encryptedKey", "saltValue")),
        c_array("c_arAgileDataSalt", b("keyData", "saltValue")),
        c_array("c_arAgileEncryptedKeyValue", b("p:encryptedKey", "encryptedKeyValue")),
        c_array("c_arAgileEncryptedVerifierInput", b("p:encryptedKey", "encryptedVerifierHashInput")),
        c_array("c_arAgileEncryptedVerifierValue", b("p:encryptedKey", "encryptedVerifierHashValue")),
        c_array("c_arAgileEncryptedHmacKey", b("dataIntegrity", "encryptedHmacKey")),
        c_array("c_arAgileEncryptedHmacValue", b("dataIntegrity", "encryptedHmacValue")),
        c_array("c_arAgileEncryptedPackage", package),
    ]


def odf():
    plain = lcg_bytes(3000, 2)  # incompressible: the checksum covers 1024 bytes
    salt, iv = os.urandom(16), os.urandom(16)
    start_key = hashlib.sha256(PASSWORD.encode("utf-8")).digest()
    key = hashlib.pbkdf2_hmac("sha1", start_key, salt, 1024, 32)

    compressor = zlib.compressobj(9, zlib.DEFLATED, -15)
    deflated = compressor.compress(plain) + compressor.flush()
    checksum = hashlib.sha256(deflated[:1024]).digest()

    # W3C padding as LibreOffice writes it: the last byte is the padding length
    pad = 16 - len(deflated) % 16
    padded = deflated + bytes(pad - 1) + bytes([pad])
    encryptor = Cipher(algorithms.AES(key), modes.CBC(iv)).encryptor()
    encrypted = encryptor.update(padded) + encryptor.finalize()
    return [
        c_array("c_arOdfSalt", salt),
        c_array("c_arOdfIv", iv),
        c_array("c_arOdfChecksum", checksum),
        c_array("c_arOdfEncrypted", encrypted),
    ]


def write_protection():
    # ECMA-376 (MS-OFFCRYPTO 2.4.2.4): H0 = H(salt + password), Hn = H(Hn-1 + n)
    salt = os.urandom(16)
    h = hashlib.sha512(salt + PASSWORD.encode("utf-16-le")).digest()
    for i in range(100000):
        h = hashlib.sha512(h + struct.pack("<I", i)).digest()

    # ODF: PBKDF2-HMAC-SHA1 of the password itself, 16 bytes
    odf_salt = os.urandom(16)
    odf_hash = hashlib.pbkdf2_hmac("sha1", ASCII_PASSWORD.encode("ascii"), odf_salt, 100000, 16)
    return [
        c_array("c_arEcmaProtectSalt", salt),
        c_array("c_arEcmaProtectHash", h),
        c_array("c_arOdfProtectSalt", odf_salt),
        c_array("c_arOdfProtectHash", odf_hash),
    ]


if __name__ == "__main__":
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "reference_vectors.h")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// SPDX-FileCopyrightText: 2026 Euro-Office contributors\n")
        f.write("// SPDX-License-Identifier: AGPL-3.0-only\n\n")
        f.write("// Generated by generate_vectors.py, do not edit.\n\n#pragma once\n\n")
        for array in agile() + odf() + write_protection():
            f.write(array + "\n")
    print("wrote", out)
