// TestEnv::SetUp() converts ExampleFiles/motion.odp to
// ExampleFiles/motion.odp-tmp.pptx via ConvertODF2OOXml() before any test
// runs (gtest runs global environments first). Nothing verified that
// fire-and-forget conversion, so a converter regression could never fail
// this suite -- it stayed green while the same class of conversion failure
// had ooxml_test quarantined (PR #166). Verify the result structurally
// rather than byte-for-byte: the committed .pptx fixtures were generated by
// an older converter build and are not byte-stable.
TEST(TestOdfConversion, MotionOdpProducesValidPptxPackage)
{
	// The TestEnv conversion must have succeeded; the file checks below
	// additionally prove a fresh package was written this run
	// (convert_single deletes any stale -tmp.pptx before converting).
	EXPECT_EQ(S_OK, GetTestEnvConvertResult());

	const std::string sOutputPath = "ExampleFiles/motion.odp-tmp.pptx";

	std::ifstream oOutput(sOutputPath.c_str(), std::ios::binary);
	ASSERT_TRUE(oOutput.is_open()) << sOutputPath << ": conversion produced no output file";

	oOutput.seekg(0, std::ios::end);
	const long long llSize = static_cast<long long>(oOutput.tellg());
	ASSERT_GT(llSize, 1024) << sOutputPath << ": conversion output is suspiciously small";

	oOutput.seekg(0);
	const std::string sBytes((std::istreambuf_iterator<char>(oOutput)), std::istreambuf_iterator<char>());
	ASSERT_TRUE(sBytes.size() >= 4 && sBytes[0] == 'P' && sBytes[1] == 'K' && sBytes[2] == '\x03' && sBytes[3] == '\x04')
		<< sOutputPath << ": output is not a zip/OPC package";
	ASSERT_NE(sBytes.find("[Content_Types].xml"), std::string::npos)
		<< sOutputPath << ": package is missing [Content_Types].xml";
	ASSERT_NE(sBytes.find("ppt/presentation.xml"), std::string::npos)
		<< sOutputPath << ": package is missing ppt/presentation.xml";
}

